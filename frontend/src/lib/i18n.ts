export const STRINGS: Record<Lang, Dict> = { en, fr };

/** Display names for the API's fixed English keys (filters still use English). */
const FR_NAMES: Record<string, string> = {
  Champions: "Champions",
  Loyal: "Fidèles",
  "Potential loyalist": "Fidèles potentiels",
  "Needs attention": "À surveiller",
  "At risk": "À risque",
  Churned: "Perdus",
  Disconnected: "Déconnectés",
  "New since baseline": "Nouveaux",
  Platinum: "Platine",
  Gold: "Or",
  Silver: "Argent",
  Bronze: "Bronze",
};

export function displayName(name: string, lang: Lang): string {
  return lang === "fr" ? (FR_NAMES[name] ?? name) : name;
}

/** Fills {placeholders} in a wording template. */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}